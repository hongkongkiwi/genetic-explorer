/**
 * Get AIMs sorted by informativeness
 */
export function getTopAIMs(count: number = 100): AIM[] {
  return [...ANCESTRY_INFORMATIVE_MARKERS]
    .sort((a, b) => b.informativeness - a.informativeness)
    .slice(0, count);
}

/**
 * Get AIMs for specific populations
 */
export function getAIMsForPopulations(populations: PopulationGroup[]): AIM[] {
  return ANCESTRY_INFORMATIVE_MARKERS.filter(aim => {
    // Return AIMs that have high frequency differences for the specified populations
    const freqs = populations.map(p => aim.frequencies[p]);
    const maxFreq = Math.max(...freqs);
    const minFreq = Math.min(...freqs);
    return maxFreq - minFreq > 0.3; // At least 30% difference
  });
}

/**
 * Get reference frequency for a specific SNP and population
 */
export function getReferenceFrequency(rsid: string, population: PopulationGroup): number | undefined {
  const aim = ANCESTRY_INFORMATIVE_MARKERS.find(a => a.rsid === rsid);
  return aim?.frequencies[population];
}

/**
 * Calculate allele frequency from genotype
 */
export function genotypeToAlleleFrequency(genotype: string, refAllele: string, altAllele: string): number {
  if (!genotype || genotype === '--' || genotype.length !== 2) {
    return 0.5; // Missing data - return neutral
  }
  
  const alleles = genotype.split('');
  let altCount = 0;
  
  for (const allele of alleles) {
    if (allele === altAllele) {
      altCount++;
    }
  }
  
  return altCount / 2; // Return frequency of alt allele
}

